"""Demand (PLAN Phase 2.2): candidate routes through the junction and routeSampler from turn counts.

    .venv/Scripts/python -m thesis_sumo.demand.build_demand --net scenario/net/site.proxy.net.xml \
        --counts data/observed/SYNTHETIC/turn_counts.csv --seed 1

- `build_candidate_routes`: one `<route>` per approach edge -> outbound edge pair the net connects at the target
  junction (any vClass), starting at the upstream end of the approach (`build_net.approach_segments`: the site
  patches split an approach into a bollard edge and the segments upstream of it), tagged with `<param key="approach">` / `<param key="movement">`. Movement codes
  follow the turn_counts schema (PLAN 5.1): r, s, l, u (SUMO dir `t`), and `illegal_l` for a left turn
  whose connections allow neither `passenger` nor `motorcycle` (the banned left, re-added for custom1 only).
- `build_demand`: reads `turn_counts.csv` (columns `TURN_COUNT_COLUMNS`, intervals of 900 s in simulation
  seconds), writes one edgeRelation turn-count file with one count attribute per vehicle type, runs
  `%SUMO_HOME%/tools/routeSampler.py` once per type (`--turn-files`, `--turn-attribute <type>`,
  `--attributes 'type="<type>" ...'`, `--prefix <type>_`, `--seed`; options from `routeSampler.py --help`,
  usage from sumo.dlr.de/docs/Tools/Turns.html "Multiple vehicle types") and merges the outputs sorted by
  depart. Types are the vType distribution ids `car`, `moto`, `moto_violator`; movement `illegal_l` ->
  `moto_violator`, any other moto count -> `moto`.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

import pandas as pd
import sumolib
from lxml import etree

from thesis_sumo.config import REPO_ROOT
from thesis_sumo.net.apply_patches import movement_of
from thesis_sumo.net.build_net import approach_edges, approach_segments, write_xml
from thesis_sumo.schema_observed import INTERVAL_S, MOVEMENTS, TURN_COUNT_COLUMNS, VCLASSES

DEMAND_DIR = REPO_ROOT / "scenario" / "demand"
# PLAN 5.1 turn_counts.csv (columns, 900 s bins, codes) from schema_observed; interval_start / interval_end are
# simulation seconds (begin of the counted window = 0)
VEHICLE_TYPES = ("car", "moto", "moto_violator")  # vTypeDistribution ids in rules/compiled/<spec_id>/vtypes.add.xml
LEGAL_VCLASSES = ("passenger", "motorcycle")
# insertion only (not driver behaviour): least occupied lane that needs the fewest lane changes, max safe speed
DEPART_ATTRS = 'departLane="best" departSpeed="max"'
SEED_STRIDE = 1000  # routeSampler seed per type = seed + k * SEED_STRIDE, so types do not share a random stream


def _schema_movement(direction: str, conns: list) -> str:
    mv = {"t": "u"}.get(movement_of(direction), movement_of(direction))
    if any(c.allows(v) for c in conns for v in LEGAL_VCLASSES):
        return mv
    if mv == "l":
        return "illegal_l"
    raise ValueError(f"movement {mv!r} is allowed for neither {LEGAL_VCLASSES}; only left turns may be "
                     f"illegal (PLAN 5.1 movement codes {MOVEMENTS})")


def movement_table(sn: sumolib.net.Net) -> dict[tuple[str, str], tuple[str, str]]:
    """(approach edge, outbound edge) -> (approach id, schema movement) for every pair the target junction
    connects, ordered by approach then outbound edge id (sidewalk edges, used only through TraCI, are left out)."""
    approach_of = {e: a for a, e in approach_edges(sn).items()}
    out = {}
    for edge in [sn.getEdge(e) for _, e in sorted((a, e) for e, a in approach_of.items())]:
        for to, conns in sorted(edge.getOutgoing().items(), key=lambda kv: kv[0].getID()):
            dirs = {c.getDirection() for c in conns}
            if len(dirs) != 1:
                raise ValueError(f"{edge.getID()} -> {to.getID()}: connections have several dirs {sorted(dirs)}")
            out[(edge.getID(), to.getID())] = (approach_of[edge.getID()], _schema_movement(dirs.pop(), conns))
    return out


def build_candidate_routes(net: Path, out: Path) -> Path:
    """Write every inbound -> outbound route through the target junction to `out`; return `out`."""
    net, out = Path(net), Path(out)
    root = etree.Element("routes")
    root.append(etree.Comment(f" generated by thesis_sumo.demand.build_demand from {net.name}: every "
                              f"inbound -> outbound pair at the target junction "))
    sn = sumolib.net.readNet(str(net))
    for (frm, to), (app, mv) in movement_table(sn).items():
        upstream = " ".join(e.getID() for e in reversed(approach_segments(sn, frm)))
        r = etree.SubElement(root, "route", id=f"{app}__{mv}", edges=f"{upstream} {to}")
        etree.SubElement(r, "param", key="approach", value=app)
        etree.SubElement(r, "param", key="movement", value=mv)
    write_xml(root, out)
    return out


def read_candidates(candidates: Path) -> dict[tuple[str, str], tuple[str, ...]]:
    """(approach, movement) -> route edges, from a file written by `build_candidate_routes`."""
    out = {}
    for r in etree.parse(str(candidates)).getroot().iter("route"):
        params = {p.get("key"): p.get("value") for p in r.findall("param")}
        key = (params["approach"], params["movement"])
        if key in out:
            raise ValueError(f"{candidates}: two routes for {key}")
        out[key] = tuple(r.get("edges").split())
    return out


def read_turn_counts(path: Path) -> pd.DataFrame:
    """turn_counts.csv checked against the PLAN 5.1 schema, plus a `type` column (vehicle type id)."""
    df = pd.read_csv(path)
    if list(df.columns) != TURN_COUNT_COLUMNS:
        raise ValueError(f"{path}: columns {list(df.columns)}, expected {TURN_COUNT_COLUMNS}")
    bad = sorted(set(df["movement"]) - set(MOVEMENTS)) + sorted(set(df["vclass"]) - set(VCLASSES))
    if bad:
        raise ValueError(f"{path}: unknown movement/vclass values {bad} (movement {MOVEMENTS}, vclass {VCLASSES})")
    width = df["interval_end"] - df["interval_start"]
    if not (width == INTERVAL_S).all():
        raise ValueError(f"{path}: every interval must span {INTERVAL_S} s (15 min), got {sorted(set(width))}")
    if (df["count"] < 0).any() or (df["count"] != df["count"].round()).any():
        raise ValueError(f"{path}: count must be a non-negative integer")
    cars = df[(df["vclass"] == "car") & (df["movement"] == "illegal_l")]
    if len(cars):
        raise ValueError(f"{path}: illegal_l is a motorcycle movement (moto_violator); car rows:\n{cars}")
    df = df.copy()
    df["type"] = df["vclass"].where(df["movement"] != "illegal_l", "moto_violator")
    return df


def _turn_file(df: pd.DataFrame, cands: dict, path: Path) -> None:
    """edgeRelation counts, one attribute per vehicle type (0 where a type has no count)."""
    missing = sorted(set(zip(df["approach"], df["movement"])) - set(cands))
    if missing:
        raise ValueError(f"turn counts for {missing} match no candidate route (movement not in the network, "
                         f"e.g. a banned turn counted as legal); available: {sorted(cands)}")
    cells = df.groupby(["interval_start", "interval_end", "approach", "movement", "type"])["count"].sum()
    root = etree.Element("data")
    for (begin, end), part in cells.groupby(level=[0, 1]):
        iv = etree.SubElement(root, "interval", id=f"{begin:g}", begin=f"{begin:g}", end=f"{end:g}")
        by_rel: dict[tuple[str, str], Counter] = {}
        for (_, _, app, mv, vtype), n in part.items():
            by_rel.setdefault((app, mv), Counter())[vtype] += int(n)
        for (app, mv), n in sorted(by_rel.items()):
            frm, to = cands[(app, mv)][-2:]  # the relation at the junction: approach edge -> exit
            etree.SubElement(iv, "edgeRelation", **{"from": frm}, to=to,
                             **{t: str(n[t]) for t in VEHICLE_TYPES})
    write_xml(root, path)


def _route_sampler(candidates: Path, turns: Path, vtype: str, seed: int, out: Path) -> None:
    script = Path(os.environ["SUMO_HOME"]) / "tools" / "routeSampler.py"
    cmd = [sys.executable, str(script), "--route-files", str(candidates), "--turn-files", str(turns),
           "--turn-attribute", vtype, "--attributes", f'type="{vtype}" {DEPART_ATTRS}',
           "--prefix", f"{vtype}_", "--seed", str(seed), "--output-file", str(out)]
    proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if proc.returncode != 0:
        raise RuntimeError(f"routeSampler failed for {vtype} (exit {proc.returncode}):\n{proc.stdout[-2000:]}"
                           f"\n{proc.stderr[-2000:]}")


def build_demand(turn_counts: Path, candidates: Path, out: Path, seed: int) -> Path:
    """Sample vehicles matching `turn_counts` from `candidates`; write them to `out`; return `out`."""
    turn_counts, candidates, out = Path(turn_counts), Path(candidates), Path(out)
    df = read_turn_counts(turn_counts)
    cands = read_candidates(candidates)
    want = df.groupby("type")["count"].sum()
    vehicles = []
    with tempfile.TemporaryDirectory(prefix="demand_") as tmp:
        turns = Path(tmp) / "turns.xml"
        _turn_file(df, cands, turns)
        for k, vtype in enumerate(VEHICLE_TYPES):
            if want.get(vtype, 0) == 0:
                continue
            part = Path(tmp) / f"{vtype}.rou.xml"
            _route_sampler(candidates, turns, vtype, seed + k * SEED_STRIDE, part)
            got = list(etree.parse(str(part), etree.XMLParser(remove_blank_text=True)).getroot().iter("vehicle"))
            if len(got) != want[vtype]:
                raise RuntimeError(f"routeSampler produced {len(got)} {vtype} vehicles for {want[vtype]} counted")
            vehicles += got
    vehicles.sort(key=lambda v: (float(v.get("depart")), v.get("id")))
    root = etree.Element("routes")
    root.append(etree.Comment(f" generated by thesis_sumo.demand.build_demand: routeSampler, seed {seed}, "
                              f"counts {turn_counts.parent.name}/{turn_counts.name}, candidates "
                              f"{candidates.name}; types reference vTypeDistribution ids {VEHICLE_TYPES} "))
    for v in vehicles:
        root.append(v)
    write_xml(root, out)
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m thesis_sumo.demand.build_demand", description=__doc__.split("\n\n")[0])
    ap.add_argument("--net", type=Path, required=True, help="site network (e.g. scenario/net/site.proxy.net.xml)")
    ap.add_argument("--counts", type=Path, required=True, help="data/observed/<day>/turn_counts.csv")
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--candidates", type=Path, default=DEMAND_DIR / "candidate_routes.rou.xml")
    ap.add_argument("--out", type=Path, default=None, help="default: scenario/demand/routes_<day>.rou.xml")
    args = ap.parse_args(argv)
    out = args.out or DEMAND_DIR / f"routes_{args.counts.parent.name}.rou.xml"
    cands = build_candidate_routes(args.net, args.candidates)
    build_demand(args.counts, cands, out, args.seed)
    n = Counter(v.get("type") for v in etree.parse(str(out)).getroot().iter("vehicle"))
    print(f"Wrote {cands} and {out}: {dict(sorted(n.items()))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
