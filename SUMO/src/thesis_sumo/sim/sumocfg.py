"""sumocfg for one run (PLAN Phase 2.3), generated from `experiment.yaml`.

`write_sumocfg` writes into `run_dir`:

- `outputs.add.xml`: an `instantInductionLoop` at the stop line of every lane entering the target junction
  (`in__<lane>`, `ENTRY_OFFSET_M` before the lane end) and at the start of every lane leaving it
  (`out__<lane>`, `EXIT_POS_M`), all into `detectors.xml`; `<timedEvent type="SaveTLSStates">` for the
  target TLS into `tls_states.xml`; and the `<poly>` `FCD_ZONE_ID`, a circle of `sim.fcd_radius_m` around
  the junction centre (the target node of the net), that filters the fcd output. SUMO keeps a vehicle
  while any part of its body overlaps the circle (checked in a run: car front bumpers up to radius + 5 m),
  so fcd rows reach radius + vehicle length.
- `run.sumocfg`, written by `sumo --save-configuration` so SUMO itself rejects any unknown option.

Options (all checked with `sumo --help`, SUMO 1.27.0, and sumo.dlr.de/docs): `--step-length`,
`--lateral-resolution` (sublane model), `--seed`, `--begin`/`--end`, `--device.rerouting.probability 0`
(`sim.device_rerouting: false`), `--tripinfo-output`, `--fcd-output` + `--fcd-output.attributes`
(incl. `posLat`, docs Simulation/Output/FCDOutput) + `--fcd-output.filter-shapes`, `--lanechange-output`,
`--statistic-output` and `--collision-output` (teleport / collision / insertion counts for the manifest),
`--collision.check-junctions true` ("Enables collisions checks on junctions"; ruling R28: the box is the M7 focus,
so collisions inside the junction must be counted; off by default), `--aggregate-warnings` (`sim.aggregate_warnings`; "Aggregate warnings of the same type whenever more than INT
occur"; `-W/--no-warnings` is never set, ruling R22).

SSM device (`sim.ssm.mode`, ruling R22; docs Simulation/Output/SSM_Device, PET needs `--device.ssm.extratime`
> 0, its default is 5 s), with `--device.ssm.measures PET` + `--device.ssm.file` when on:
- `off` (calibration, LLM loop, Optuna): no `device.ssm.*` option at all. The default
  `--device.ssm.probability` is -1 (`sumo --save-template`: not set), so no vehicle gets a device and SUMO
  does no SSM work. `--device.ssm.probability 0` (ruling R22's wording) is equivalent: checked on PROXY_D1
  B0 300 s, both give byte-identical tripinfo records, no SSM file and the same wall time (11-13 s; 55 s and
  120k warning lines with probability 1).
- `violators`: `--device.ssm.explicit` = ids of the `VIOLATOR_TYPE` vehicles in the routes file
  ("Assign a 'ssm' device to named vehicles").
- `all`: `--device.ssm.probability 1` (every vehicle; on the proxy net ~1.5 M warning lines per hour).

`--ignore-route-errors` is never set; teleports and collisions stay at SUMO defaults (never hidden).
Input paths are absolute; output paths are bare file names, which SUMO resolves relative to the config
file (outputs) and to `outputs.add.xml` (detectors, TLS states), i.e. all land in `run_dir`.
"""

from __future__ import annotations

import gzip
import math
import subprocess
from pathlib import Path

import sumolib
from lxml import etree

from thesis_sumo.net.build_net import inbound_edges, target_node, target_tls, write_xml

CFG_NAME = "run.sumocfg"
FCD_ZONE_ID = "fcd_zone"
FCD_ZONE_VERTICES = 72
FCD_ATTRIBUTES = ("x", "y", "angle", "type", "speed", "pos", "lane", "posLat", "speedLat", "acceleration")
ENTRY_OFFSET_M = 0.1  # entry loop this far before the end of the inbound lane (the stop line)
EXIT_POS_M = 0.1      # exit loop this far after the start of the outbound lane
SSM_MODES = ("off", "violators", "all")
VIOLATOR_TYPE = "moto_violator"  # vType distribution id of the illegal left-turners (build_demand.VEHICLE_TYPES)
OUTPUT_FILES = {
    "outputs-additional": "outputs.add.xml",
    "detectors": "detectors.xml",
    "tls-states": "tls_states.xml",
    "tripinfo-output": "tripinfo.xml",
    "fcd-output": "fcd.xml.gz",
    "lanechange-output": "lanechange.xml",
    "device.ssm.file": "ssm.xml",
    "statistic-output": "statistics.xml",
    "collision-output": "collisions.xml",
}


def _circle(cx: float, cy: float, r: float, n: int = FCD_ZONE_VERTICES) -> str:
    pts = [(cx + r * math.cos(2 * math.pi * k / n), cy + r * math.sin(2 * math.pi * k / n)) for k in range(n)]
    return " ".join(f"{x:.2f},{y:.2f}" for x, y in pts + pts[:1])


def write_output_additional(net: Path, out: Path, fcd_radius_m: float) -> Path:
    """Detectors, TLS-state event and fcd zone polygon for the target junction of `net`."""
    sn = sumolib.net.readNet(str(net))
    tls = target_tls(sn)
    node = target_node(tls)
    root = etree.Element("additional")
    root.append(etree.Comment(" generated by thesis_sumo.sim.sumocfg "))
    det = OUTPUT_FILES["detectors"]
    for edge in sorted(inbound_edges(node), key=lambda e: e.getID()):
        for lane in edge.getLanes():
            etree.SubElement(root, "instantInductionLoop", id=f"in__{lane.getID()}", lane=lane.getID(),
                             pos=f"{lane.getLength() - ENTRY_OFFSET_M:.2f}", file=det)
    for edge in sorted(node.getOutgoing(), key=lambda e: e.getID()):
        for lane in edge.getLanes():
            etree.SubElement(root, "instantInductionLoop", id=f"out__{lane.getID()}", lane=lane.getID(),
                             pos=f"{EXIT_POS_M:.2f}", file=det)
    etree.SubElement(root, "timedEvent", type="SaveTLSStates", source=tls.getID(), dest=OUTPUT_FILES["tls-states"])
    cx, cy = node.getCoord()
    etree.SubElement(root, "poly", id=FCD_ZONE_ID, type="fcd_zone", color="0,0,255", fill="0", layer="-1",
                     shape=_circle(cx, cy, fcd_radius_m))
    write_xml(root, out)
    return out


def violator_ids(routes: Path) -> list[str]:
    """Ids of the `VIOLATOR_TYPE` vehicles in a routes file (`.xml` or `.xml.gz`), in file order."""
    routes = Path(routes)
    with (gzip.open(routes, "rb") if routes.suffix == ".gz" else routes.open("rb")) as f:
        ids = []
        for _, el in etree.iterparse(f, tag="vehicle"):
            if el.get("type") == VIOLATOR_TYPE:
                ids.append(el.get("id"))
            el.clear()
    return ids


def ssm_options(mode, routes: Path) -> dict:
    """sumo options for `sim.ssm.mode` (see the module docstring)."""
    if isinstance(mode, bool):
        raise ValueError(f"experiment.yaml sim.ssm.mode is {mode!r}: YAML reads an unquoted off/on as a boolean, "
                         f"quote it (one of {SSM_MODES})")
    if mode not in SSM_MODES:
        raise ValueError(f"experiment.yaml sim.ssm.mode must be one of {SSM_MODES}, got {mode!r}")
    if mode == "off":
        return {}
    if mode == "all":
        who = {"device.ssm.probability": 1}
    else:
        ids = violator_ids(routes)
        if not ids:
            raise ValueError(f"sim.ssm.mode violators: no vehicle of type {VIOLATOR_TYPE!r} in {routes}")
        who = {"device.ssm.explicit": ",".join(ids)}
    return {**who, "device.ssm.measures": "PET", "device.ssm.file": OUTPUT_FILES["device.ssm.file"]}


def write_sumocfg(run_dir: Path, net: Path, routes: Path, additionals: list[Path], seed: int, exp: dict) -> Path:
    """Write `run_dir/run.sumocfg` (+ `outputs.add.xml`) for one seed; return the config path."""
    run_dir = Path(run_dir).resolve()  # sumo runs with cwd=run_dir, so the config path below must be absolute
    run_dir.mkdir(parents=True, exist_ok=True)
    sim = exp["sim"]
    outputs_add = write_output_additional(net, run_dir / OUTPUT_FILES["outputs-additional"], sim["fcd_radius_m"])
    adds = [Path(a).resolve() for a in additionals] + [outputs_add.resolve()]
    opts = {
        "net-file": Path(net).resolve(),
        "route-files": Path(routes).resolve(),
        "additional-files": ",".join(str(a) for a in adds),
        "begin": sim["begin_s"],
        "end": sim["end_s"],
        "step-length": sim["step_length_s"],
        "lateral-resolution": sim["lateral_resolution_m"],
        "seed": int(seed),
        "device.rerouting.probability": 1 if sim["device_rerouting"] else 0,
        "tripinfo-output": OUTPUT_FILES["tripinfo-output"],
        "fcd-output": OUTPUT_FILES["fcd-output"],
        "fcd-output.attributes": ",".join(FCD_ATTRIBUTES),
        "fcd-output.filter-shapes": FCD_ZONE_ID,
        "lanechange-output": OUTPUT_FILES["lanechange-output"],
        **ssm_options(sim["ssm"]["mode"], routes),
        "statistic-output": OUTPUT_FILES["statistic-output"],
        "collision-output": OUTPUT_FILES["collision-output"],
        "collision.check-junctions": "true",
        "no-step-log": "true",
        "aggregate-warnings": int(sim["aggregate_warnings"]),
    }
    cfg = run_dir / CFG_NAME
    cmd = [sumolib.checkBinary("sumo")]
    for key, value in opts.items():
        cmd += [f"--{key}", str(value)]
    cmd += ["--save-configuration", str(cfg)]
    proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace", cwd=run_dir)
    if proc.returncode != 0 or not cfg.is_file():
        raise RuntimeError(f"sumo --save-configuration failed (exit {proc.returncode}):\n{proc.stderr[-2000:]}")
    return cfg
